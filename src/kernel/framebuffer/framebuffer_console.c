static void draw_char_at(uint32_t x, uint32_t y, char c, uint32_t color) {
    if (!console.framebuffer || x + CHAR_WIDTH > console.width || y + CHAR_HEIGHT > console.height) {
        return;
    }

    const uint8_t* font_data = console_font[(unsigned char)c];

    for (uint32_t row = 0; row < CHAR_HEIGHT; row++) {
        uint8_t byte = font_data[row];
        uint32_t* scanline = console.framebuffer + (y + row) * (console.pitch / sizeof(uint32_t)) + x;

        for (uint32_t column = 0; column < CHAR_WIDTH; column++) {
            if (byte & (0x80 >> column)) {
                scanline[column] = color;
            }
        }
    }
}

static void console_scroll_up(void) {
    if (!console.framebuffer) {
        return;
    }

    uint32_t line_height = CHAR_HEIGHT + 2;
    uint32_t srcoll_bytes = line_height * console.pitch;
    uint32_t* source = console.framebuffer + (srcoll_bytes / sizeof(uint32_t));
    uint32_t* destination = console.framebuffer;
    uint32_t total_pixels = (console.height - line_height) * (console.pitch / sizeof(uint32_t));

    for (uint32_t i = 0; i < total_pixels; i++) {
        destination[i] = source[i];
    }

    uint32_t clear_start = (console.height - line_height) * (console.pitch / sizeof(uint32_t));
    uint32_t clear_end = console.height * (console.pitch / sizeof(uint32_t));

    for (uint32_t i = clear_start; i < clear_end; i++) {
        console.framebuffer[i] = 0xFF000000;
    }
}

void framebuffer_console_init(void) {
    Framebuffer framebuffer = framebuffer_get();
    console.framebuffer = (volatile uint32_t*)framebuffer.address;
    console.width = framebuffer.width;
    console.height = framebuffer.height;
    console.pitch = framebuffer.pitch;
    console.cursor_x = 0;
    console.cursor_y = 0;

    if (console.framebuffer) {
        uint32_t total_pixels = console.height * (console.pitch / sizeof(uint32_t));

        for (uint32_t i = 0; i < total_pixels; i++) {
            console.framebuffer[i] = 0xFF000000;
        }
    }
}

void framebuffer_console_print(const char* text) {
    if (!console.framebuffer || !text) {
        return;
    }

    uint32_t line_height = CHAR_HEIGHT + 2;
    uint32_t text_color = 0xFFFFFFFF;

    for (const char* p = text; *p != '\0'; p++) {
        if (*p == '\n') {
            console.cursor_x = 0;
            console.cursor_y += line_height;
        }
        else {
            draw_char_at(console.cursor_x, console.cursor_y, *p, text_color);
            console.cursor_x += CHAR_WIDTH;
        }

        if (console.cursor_x + CHAR_WIDTH > console.width) {
            console.cursor_x = 0;
            console.cursor_y += line_height;
        }

        if (console.cursor_y + line_height > console.height) {
            console_scroll_up();
            console.cursor_y -= line_height;
        }
    }
}